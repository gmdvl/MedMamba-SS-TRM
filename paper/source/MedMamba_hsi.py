"""
MedMamba_hsi.py

Hyperspectral-image (HSI) variant of MedMamba.py.

This is a standalone copy of the original VSSM/SS2D/Mamba backbone so
the RGB-oriented MedMamba.py is left untouched. The Mamba/SS2D math is
unchanged from the original; the only real adaptations are:

1. ``in_chans`` is meant to be set to the number of spectral bands
   (e.g. 32) instead of 3. This already worked in the original file
   (PatchEmbed2D's Conv2d takes an arbitrary channel count), it is
   just exposed/defaulted here for HSI use.

2. ``patch_size`` defaults to 1 instead of 4. HSI patch datasets are
   frequently tiny pixel-neighborhood cubes (e.g. 11x11xBANDS) rather
   than 224x224 photographs. A stride-4 patch embedding would throw
   away almost all spatial context on an 11x11 input (11x11 -> 2x2
   before the backbone even starts). A patch_size of 1 keeps the full
   spatial resolution and lets PatchMerging2D perform the (gentler,
   learned) downsampling instead.

3. The module-level demo/instantiation block from the original file
   (which ran on every `import MedMamba`, required CUDA, and had
   nothing to do with HSI) is removed. Use `build_hsi_vssm(...)` or
   `VSSM(...)` directly, or run this file to execute a small guarded
   self-test under `if __name__ == "__main__":`.

Note: this backbone fuses all spectral bands together in the very
first convolution (early fusion). It has no dedicated mechanism for
treating the spectral axis as its own sequence the way some
HSI-specific Mamba variants do -- SS2D only scans the two spatial
directions. For the tiny-patch, many-band, few-class setting typical
of HSI classification, prefer small `dims`/`depths` (see
`build_hsi_vssm` defaults) over the original MedMamba-T/S/B sizes,
which were tuned for 224x224 natural/medical images and are heavily
overparameterized for an 11x11xN patch classification task.
"""

